const menuButton = document.querySelector('.menu-button');
const nav = document.querySelector('#site-nav');
function closeMenu(returnFocus = false) {
  nav.classList.remove('is-open');
  menuButton.setAttribute('aria-expanded', 'false');
  menuButton.textContent = '選單';
  if (returnFocus) menuButton.focus();
}
menuButton.addEventListener('click', () => {
  const open = !nav.classList.contains('is-open');
  nav.classList.toggle('is-open', open);
  menuButton.setAttribute('aria-expanded', String(open));
  menuButton.textContent = open ? '關閉' : '選單';
});
nav.addEventListener('click', event => {
  if (event.target.closest('a')) closeMenu();
});
document.addEventListener('keydown', event => {
  if (event.key === 'Escape' && nav.classList.contains('is-open')) closeMenu(true);
});
window.addEventListener('resize', () => {
  if (window.innerWidth > 1100) closeMenu();
});

const lightbox = document.querySelector('#photo-viewer');
const viewerImage = lightbox.querySelector('img');
const viewerTitle = lightbox.querySelector('#viewer-title');
const viewerCaption = lightbox.querySelector('#viewer-caption');
const viewerCount = lightbox.querySelector('.lightbox-count');
const viewerSeriesName = lightbox.querySelector('#viewer-series-name');
const viewerRoomName = lightbox.querySelector('#viewer-room-name');
const inquiry = lightbox.querySelector('.lightbox-inquiry');
const previous = lightbox.querySelector('[data-previous]');
const next = lightbox.querySelector('[data-next]');
const previousSeries = lightbox.querySelector('[data-previous-series]');
const nextSeries = lightbox.querySelector('[data-next-series]');
const closeButton = lightbox.querySelector('[data-close]');
const viewerStage = lightbox.querySelector('.lightbox-image');
const viewerStatus = lightbox.querySelector('.lightbox-status');
const pagePhotos = [...document.querySelectorAll('[data-photo]')];
const pageSeriesIndex = SERIES_CATALOG.findIndex(series => series.id === document.body.dataset.series);
let seriesIndex = pageSeriesIndex;
let photoIndex = 0;
let originButton = null;
let photoRequest = 0;
let touchStart = null;

function wrapIndex(index, length) {
  return ((index % length) + length) % length;
}

function showPhoto(index) {
  const series = SERIES_CATALOG[seriesIndex];
  if (!series) return;
  photoIndex = wrapIndex(index, series.photos.length);
  const photo = series.photos[photoIndex];
  const request = ++photoRequest;
  touchStart = null;

  // Change all descriptive state together, and hide the previous image immediately.
  viewerImage.hidden = true;
  viewerImage.removeAttribute('src');
  viewerImage.alt = photo.alt;
  viewerTitle.textContent = photo.title;
  viewerCaption.textContent = photo.caption;
  viewerSeriesName.textContent = series.name;
  viewerRoomName.textContent = photo.room;
  viewerCount.textContent = `第 ${seriesIndex + 1} / ${SERIES_CATALOG.length} 套 · 第 ${photoIndex + 1} / ${series.photos.length} 張`;
  inquiry.href = `https://wa.me/85291568082?text=${encodeURIComponent('Anson，你好！我想查詢「' + photo.title + '」的設計／工程。')}`;
  previous.disabled = next.disabled = series.photos.length < 2;
  previousSeries.disabled = nextSeries.disabled = SERIES_CATALOG.length < 2;
  viewerStatus.textContent = '相片載入中…';
  viewerStatus.hidden = false;
  viewerStage.setAttribute('aria-busy', 'true');

  const loadingImage = new Image();
  loadingImage.decoding = 'async';
  const isCurrentRequest = () => request === photoRequest && lightbox.open;
  const showLoadError = () => {
    if (!isCurrentRequest()) return;
    viewerStatus.textContent = '相片暫時無法載入，請稍後再試，或查看其他相片。';
    viewerStatus.hidden = false;
    viewerStage.setAttribute('aria-busy', 'false');
  };
  loadingImage.onload = async () => {
    if (!isCurrentRequest()) return;
    if (typeof loadingImage.decode === 'function') {
      try {
        await loadingImage.decode();
      } catch {
        showLoadError();
        return;
      }
    }
    // A newer selection or close can happen while decode() is pending.
    if (!isCurrentRequest()) return;
    viewerImage.src = loadingImage.src;
    viewerImage.hidden = false;
    viewerStatus.hidden = true;
    viewerStage.setAttribute('aria-busy', 'false');
  };
  loadingImage.onerror = showLoadError;
  loadingImage.src = photo.full;
}

function showSeries(index) {
  seriesIndex = wrapIndex(index, SERIES_CATALOG.length);
  // All suites use the same overview/living/bedrooms/kitchen/bathroom order.
  showPhoto(photoIndex);
}

function closeViewer() {
  lightbox.close();
}

pagePhotos.forEach((button, index) => button.addEventListener('click', () => {
  // Each reopen belongs to the page and room the visitor actually selected.
  originButton = button;
  seriesIndex = pageSeriesIndex;
  closeMenu();
  lightbox.showModal();
  showPhoto(index);
  closeButton.focus({preventScroll: true});
}));

previous.addEventListener('click', () => showPhoto(photoIndex - 1));
next.addEventListener('click', () => showPhoto(photoIndex + 1));
previousSeries.addEventListener('click', () => showSeries(seriesIndex - 1));
nextSeries.addEventListener('click', () => showSeries(seriesIndex + 1));
closeButton.addEventListener('click', closeViewer);
lightbox.addEventListener('cancel', event => {
  event.preventDefault();
  closeViewer();
});
lightbox.addEventListener('click', event => {
  if (event.target !== lightbox) return;
  const rect = lightbox.getBoundingClientRect();
  if (event.clientX < rect.left || event.clientX > rect.right || event.clientY < rect.top || event.clientY > rect.bottom) closeViewer();
});
lightbox.addEventListener('keydown', event => {
  if (event.key === 'Escape') {
    event.preventDefault();
    closeViewer();
    return;
  }
  if (event.altKey || event.ctrlKey || event.metaKey || event.shiftKey) return;
  if (event.key === 'ArrowLeft' || event.key === 'ArrowRight') {
    event.preventDefault();
    const direction = event.key === 'ArrowRight' ? 1 : -1;
    showPhoto(photoIndex + direction);
  }
});
lightbox.addEventListener('close', () => {
  if (lightbox.open) return;
  photoRequest++;
  touchStart = null;
  viewerImage.hidden = true;
  viewerImage.removeAttribute('src');
  viewerImage.alt = '';
  viewerStatus.hidden = true;
  viewerStage.setAttribute('aria-busy', 'false');
  viewerTitle.textContent = '';
  viewerCaption.textContent = '';
  viewerSeriesName.textContent = '';
  viewerRoomName.textContent = '';
  viewerCount.textContent = '';
  inquiry.href = 'https://wa.me/85291568082';
  seriesIndex = pageSeriesIndex;
  photoIndex = 0;
  originButton?.focus({preventScroll: true});
});

viewerImage.decoding = 'async';
viewerImage.addEventListener('touchstart', event => {
  touchStart = {x: event.changedTouches[0].clientX, y: event.changedTouches[0].clientY};
}, {passive: true});
viewerImage.addEventListener('touchend', event => {
  if (!touchStart) return;
  const dx = event.changedTouches[0].clientX - touchStart.x;
  const dy = event.changedTouches[0].clientY - touchStart.y;
  if (Math.abs(dx) > 65 && Math.abs(dx) > Math.abs(dy) * 1.5) showPhoto(photoIndex + (dx < 0 ? 1 : -1));
  touchStart = null;
}, {passive: true});
viewerImage.addEventListener('touchcancel', () => { touchStart = null; }, {passive: true});
